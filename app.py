# Preprocess image
def preprocess_image(image):
    # Convert PIL image to numpy array
    img = np.array(image)
    
    # Convert to RGB if needed (before resizing)
    if len(img.shape) == 2:
        img = cv2.cvtColor(img, cv2.COLOR_GRAY2RGB)
    elif img.shape[2] == 4:
        img = cv2.cvtColor(img, cv2.COLOR_RGBA2RGB)
    
    # Resize to model input size (224x224 for EfficientNetB3)
    img = cv2.resize(img, (224, 224))
    
    # Convert to float32
    img = img.astype('float32')
    
    # Add batch dimension
    img = np.expand_dims(img, axis=0)
    
    # Apply EfficientNet preprocessing (this is crucial!)
    # EfficientNet expects images in range [0, 255] and applies its own normalization
    img = preprocess_input(img)
    
    return img

