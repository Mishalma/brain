# Generate medical report using Gemini
def generate_medical_report(image, prediction_result, confidence, probabilities):
    try:
        model = genai.GenerativeModel('gemini-2.0-flash-exp')
        
        # Convert PIL image to bytes
        img_byte_arr = io.BytesIO()
        image.save(img_byte_arr, format='PNG')
        img_byte_arr = img_byte_arr.getvalue()
        
        prompt = f"""You are an expert radiologist. Analyze this brain MRI scan and provide a detailed medical report.

AI Model Prediction: {prediction_result}
Confidence Score: {confidence:.2f}%
Probability Distribution:
- No Tumor: {probabilities[0]:.2f}%
- Tumor Detected: {probabilities[1]:.2f}%

Please provide a structured medical report with the following sections:

1. CLINICAL FINDINGS: Describe what you observe in the MRI scan
2. AI ANALYSIS SUMMARY: Interpret the AI model's prediction
3. RADIOLOGICAL OBSERVATIONS: Detail any notable features, abnormalities, or patterns
4. RECOMMENDATIONS: Suggest next steps for the physician
5. ADDITIONAL NOTES: Any other relevant observations

Keep the report professional, concise, and medically accurate. Use appropriate medical terminology."""

        response = model.generate_content([prompt, {'mime_type': 'image/png', 'data': img_byte_arr}])
        return response.text
    except Exception as e:
        # Fallback to basic report if Gemini API fails
        return generate_fallback_report(prediction_result, confidence, probabilities, str(e))

